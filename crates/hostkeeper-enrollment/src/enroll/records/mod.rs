/// The store's messages, generated by build.rs from `proto/`: the records [`Records`] keeps.
/// Field 1 of each is `schema`, which only a file needs: a record kept elsewhere carries the
/// value the store writes, 1.
#[allow(
    clippy::all,
    dead_code,
    reason = "generated code follows the proto's shapes and comments, not clippy's style, and \
              carries accessors and enum conversions the store does not call"
)]
pub mod pb {
    include!(concat!(
        env!("OUT_DIR"),
        "/hostkeeper.enrollment.store.v1.rs"
    ));
}

/// One record a commit writes.
#[derive(Clone, Debug, PartialEq)]
#[expect(
    clippy::large_enum_variant,
    reason = "a commit holds a handful of records, built and dropped at once; boxing the request \
              would add an allocation and a dereference at every use for no memory that matters"
)]
pub enum Record {
    /// Kept under its `request_id`.
    Request(pb::Request),
    /// Kept under its `request_id`: the certificate of the request's current round.
    Issued(pb::Issued),
    /// Kept under its `host_id`.
    Host(pb::Host),
    /// Kept under its `host_id`.
    Deny(pb::Deny),
    /// Kept under its `nonce_sha256`.
    MacNonce(pb::MacNonce),
}

/// Which record: what a record is kept under, and what [`Records::place`] names.
#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum RecordKey {
    Request(KeyHash),
    Issued(KeyHash),
    Host(HostId),
    Deny(HostId),
    MacNonce(MacNonceHash),
    /// The serial counter, of which there is one.
    Serial,
}

impl Record {
    /// The key the record is kept under, read from its fields.
    ///
    /// # Errors
    /// [`StoreError::Unkeyed`] when that field does not parse: a request id or nonce hash that
    /// is not 32 bytes, a host id outside its grammar. No implementation keeps such a record.
    pub fn key(&self) -> Result<RecordKey, StoreError> {
        let refused = |kind: &'static str| StoreError::Unkeyed(kind);
        match self {
            Record::Request(request) => KeyHash::from_bytes(&request.request_id)
                .map(RecordKey::Request)
                .ok_or_else(|| refused("request")),
            Record::Issued(issued) => KeyHash::from_bytes(&issued.request_id)
                .map(RecordKey::Issued)
                .ok_or_else(|| refused("issued")),
            Record::Host(host) => HostId::parse(&host.host_id)
                .map(RecordKey::Host)
                .map_err(|_| refused("host")),
            Record::Deny(deny) => HostId::parse(&deny.host_id)
                .map(RecordKey::Deny)
                .map_err(|_| refused("deny")),
            Record::MacNonce(nonce) => MacNonceHash::from_bytes(&nonce.nonce_sha256)
                .map(RecordKey::MacNonce)
                .ok_or_else(|| refused("mac nonce")),
        }
    }
}

/// The exclusion [`Records::lock`] gives, held until it is dropped: a file lock for
/// [`FileRecords`], nothing beyond the store's own mutex for records that keep other processes
/// off by other means.
#[derive(Debug)]
pub struct RecordsLock {
    _file: Option<FileLock>,
}

impl RecordsLock {
    /// No exclusion beyond the store's mutex.
    pub fn in_process() -> RecordsLock {
        RecordsLock { _file: None }
    }

    /// The `flock` of `file`, released when this is dropped.
    pub fn file(file: FileLock) -> RecordsLock {
        RecordsLock { _file: Some(file) }
    }
}

/// Where the enrollment store's records are durable.
///
/// Every load returns a record exactly as the last commit that wrote it left it, and `None` for
/// one never written: a record is never deleted. A write is durable when it returns `Ok`. The
/// store calls every write, and every read it decides by, under its mutex and [`Records::lock`].
pub trait Records: Send + Sync + fmt::Debug {
    /// Keeps other processes off the records while the store decides and writes.
    ///
    /// # Errors
    /// [`StoreError`] when the exclusion cannot be taken.
    fn lock(&self) -> Result<RecordsLock, StoreError>;

    /// Where `key` is kept, as an error about it names it: a file's path, or a name of the
    /// record for records not kept in files.
    fn place(&self, key: &RecordKey) -> PathBuf;

    /// The request `id`.
    ///
    /// # Errors
    /// [`StoreError`] when it cannot be read.
    fn request(&self, id: &KeyHash) -> Result<Option<pb::Request>, StoreError>;

    /// Every request, each with the id it is kept under, in the order of their ids. The store
    /// checks every one it is given, whatever it then looks for, so a list is as strict as a
    /// read of each.
    ///
    /// # Errors
    /// [`StoreError`] when one cannot be read.
    fn requests(&self) -> Result<Vec<(KeyHash, pb::Request)>, StoreError>;

    /// The issued certificate of request `id`.
    ///
    /// # Errors
    /// [`StoreError`] when it cannot be read.
    fn issued(&self, id: &KeyHash) -> Result<Option<pb::Issued>, StoreError>;

    /// The host `host`.
    ///
    /// # Errors
    /// [`StoreError`] when it cannot be read.
    fn host(&self, host: &HostId) -> Result<Option<pb::Host>, StoreError>;

    /// The ids of every host, sorted.
    ///
    /// # Errors
    /// [`StoreError`] when they cannot be listed.
    fn host_ids(&self) -> Result<Vec<HostId>, StoreError>;

    /// The deny row of `host`.
    ///
    /// # Errors
    /// [`StoreError`] when it cannot be read.
    fn deny(&self, host: &HostId) -> Result<Option<pb::Deny>, StoreError>;

    /// The Mac nonce of SHA-256 `hash`, with the request that consumed it, if one did.
    ///
    /// # Errors
    /// [`StoreError`] when it cannot be read.
    fn mac_nonce(&self, hash: &MacNonceHash) -> Result<Option<pb::MacNonce>, StoreError>;

    /// Writes `records`, each over the record of its key, in one commit.
    ///
    /// # Errors
    /// [`StoreError`] when they cannot be written; [`StoreError::Unkeyed`] for a record whose key
    /// does not parse ([`Record::key`]). What a failed commit leaves is the implementation's to
    /// say.
    fn commit(&self, records: &[Record]) -> Result<(), StoreError>;

    /// Takes the next serial ([`FIRST_SERIAL`](super::FIRST_SERIAL) when none was taken) and
    /// records the one after it; with `reserving`, also writes that request with its `serial`
    /// set to the one taken. The serial is never taken again once this returns `Ok`.
    ///
    /// # Errors
    /// [`StoreError`] when the counter or the request cannot be read or written.
    fn take_serial(&self, reserving: Option<&pb::Request>) -> Result<u64, StoreError>;

    /// Writes `host`, as the store loaded it, with its first heartbeat at `at_unix`.
    ///
    /// # Errors
    /// [`StoreError`] when it cannot be written.
    fn set_first_heartbeat(&self, host: &pb::Host, at_unix: u64) -> Result<(), StoreError>;

    /// Writes `host`, as the store loaded it, serving since `at_unix`.
    ///
    /// # Errors
    /// [`StoreError`] when it cannot be written.
    fn set_first_serving(&self, host: &pb::Host, at_unix: u64) -> Result<(), StoreError>;

    /// Writes `host`, as the store loaded it, marked duplicate.
    ///
    /// # Errors
    /// [`StoreError`] when it cannot be written.
    fn set_duplicate(&self, host: &pb::Host) -> Result<(), StoreError>;
}
