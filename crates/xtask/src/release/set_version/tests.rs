fn v(text: &str) -> Version {
    text.parse().expect("a version")
}

fn put(root: &Path, path: &str, text: &str) {
    let file = root.join(path);
    std::fs::create_dir_all(file.parent().expect("a parent")).expect("create the directory");
    std::fs::write(file, text).expect("write the file");
}

fn get(root: &Path, path: &str) -> String {
    std::fs::read_to_string(root.join(path)).expect("read the file")
}

fn package(name: &str) -> String {
    format!("[package]\nname = \"{name}\"\nversion.workspace = true\n")
}

/// A workspace like `MANIFEST` and `LOCK`: members `a` and `b` under `crates/`, `extra` under
/// `tools/`, a directory under `crates/` with no manifest and a file there.
fn workspace(root: &Path) {
    put(root, "Cargo.toml", MANIFEST);
    put(root, "Cargo.lock", LOCK);
    put(root, "crates/a/Cargo.toml", &package("a"));
    put(root, "crates/b/Cargo.toml", &package("b"));
    put(root, "crates/notes/readme.txt", "not a member");
    put(root, "crates/loose.txt", "not a directory");
    put(root, "tools/extra/Cargo.toml", &package("extra"));
}

/// Catches: a version written into the wrong table or line, a registry block of a member's name
/// rewritten, or any other byte of either file changed.
#[test]
fn set_version_writes_the_manifest_and_every_member_block_and_nothing_else() {
    let dir = scratch("set-version-writes");
    workspace(&dir);
    assert_eq!(
        set_version(&dir, &v("0.2.7")),
        Ok(vec![
            "Cargo.toml and Cargo.lock: the workspace and its 3 members are 0.2.7".to_owned()
        ])
    );
    assert_eq!(get(&dir, "Cargo.toml"), MANIFEST_AFTER);
    assert_eq!(get(&dir, "Cargo.lock"), LOCK_AFTER);
}

/// Catches: a second run with the same version changing any byte of either file.
#[test]
fn set_version_twice_with_one_version_changes_nothing_more() {
    let dir = scratch("set-version-idempotent");
    workspace(&dir);
    set_version(&dir, &v("0.2.7")).expect("the first run");
    set_version(&dir, &v("0.2.7")).expect("the second run");
    assert_eq!(get(&dir, "Cargo.toml"), MANIFEST_AFTER);
    assert_eq!(get(&dir, "Cargo.lock"), LOCK_AFTER);
}

/// Catches: a final member block whose version line has no line break being skipped or given
/// one.
#[test]
fn a_member_version_line_at_the_end_of_the_file_keeps_having_no_line_break() {
    let dir = scratch("set-version-last-line");
    put(
        &dir,
        "Cargo.toml",
        "[workspace]\nmembers = [\"m\"]\n[workspace.package]\nversion = \"0.1.0\"",
    );
    put(
        &dir,
        "Cargo.lock",
        "[[package]]\nname = \"m\"\nversion = \"0.1.0\"",
    );
    put(&dir, "m/Cargo.toml", &package("m"));
    set_version(&dir, &v("3.4.5")).expect("set the version");
    assert_eq!(
        get(&dir, "Cargo.lock"),
        "[[package]]\nname = \"m\"\nversion = \"3.4.5\""
    );
    assert_eq!(
        get(&dir, "Cargo.toml"),
        "[workspace]\nmembers = [\"m\"]\n[workspace.package]\nversion = \"3.4.5\""
    );
}

/// Catches: a member that sets its own version being left out of the workspace version
/// silently.
#[test]
fn a_member_that_does_not_inherit_the_version_is_refused_and_nothing_is_written() {
    let dir = scratch("set-version-no-inherit");
    workspace(&dir);
    put(
        &dir,
        "crates/b/Cargo.toml",
        "[package]\nname = \"b\"\nversion = \"0.1.0\"\n",
    );
    assert_eq!(
        set_version(&dir, &v("0.2.7")),
        Err(Error::Failed(
            "crates/b/Cargo.toml does not inherit the workspace version: its [package] needs version.workspace = true".to_owned()
        ))
    );
    assert_eq!(get(&dir, "Cargo.toml"), MANIFEST);
    assert_eq!(get(&dir, "Cargo.lock"), LOCK);
}

/// Catches: a member missing from the lock file passing, which would make a locked build fail
/// after the manifest was already rewritten.
#[test]
fn a_member_missing_from_the_lock_file_is_refused_and_nothing_is_written() {
    let dir = scratch("set-version-not-locked");
    workspace(&dir);
    put(&dir, "crates/c/Cargo.toml", &package("c"));
    assert_eq!(
        set_version(&dir, &v("0.2.7")),
        Err(Error::Failed("c is not in Cargo.lock".to_owned()))
    );
    assert_eq!(get(&dir, "Cargo.toml"), MANIFEST);
    assert_eq!(get(&dir, "Cargo.lock"), LOCK);
}

/// Catches: a lock block of a member with no version line passing as written.
#[test]
fn a_member_block_without_a_version_line_is_refused() {
    let dir = scratch("set-version-block-no-version");
    workspace(&dir);
    put(&dir, "Cargo.lock", "[[package]]\nname = \"a\"\n");
    assert_eq!(
        set_version(&dir, &v("0.2.7")),
        Err(Error::Failed(
            "Cargo.lock: the block of a has no version".to_owned()
        ))
    );
}

/// Catches: a root manifest without a workspace package version line passing, or a version line
/// of another table being taken for it.
#[test]
fn a_manifest_without_a_workspace_package_version_line_is_refused() {
    let dir = scratch("set-version-no-line");
    workspace(&dir);
    let refusal: Result<Vec<String>, Error> = Err(Error::Failed(
        "Cargo.toml has no version line in [workspace.package]".to_owned(),
    ));
    let no_line = MANIFEST.replace("version=\"0.1.0\"\n", "");
    put(&dir, "Cargo.toml", &no_line);
    assert_eq!(set_version(&dir, &v("0.2.7")), refusal);
    let no_table = MANIFEST.replace("[workspace.package]", "[workspace.other]");
    put(&dir, "Cargo.toml", &no_table);
    assert_eq!(set_version(&dir, &v("0.2.7")), refusal);
    assert_eq!(get(&dir, "Cargo.lock"), LOCK);
}

/// Catches: a missing manifest or lock file reported without the path, or the lock file being
/// read after the manifest was written.
#[test]
fn a_missing_manifest_or_lock_file_is_an_io_error_naming_it() {
    let dir = scratch("set-version-missing");
    let missing = |name: &str| -> Result<Vec<String>, Error> {
        let path = dir.join(name);
        Err(Error::Io {
            what: format!("read {}", path.display()),
            why: std::fs::read_to_string(&path)
                .expect_err("absent")
                .to_string(),
        })
    };
    assert_eq!(set_version(&dir, &v("0.2.7")), missing("Cargo.toml"));
    put(&dir, "Cargo.toml", MANIFEST);
    assert_eq!(set_version(&dir, &v("0.2.7")), missing("Cargo.lock"));
}

/// Catches: a manifest that is not TOML, or one with no member list, or with a member entry
/// that is not a path, being accepted.
#[test]
fn a_manifest_that_is_not_a_workspace_manifest_is_refused() {
    let dir = scratch("set-version-bad-manifest");
    put(&dir, "Cargo.lock", LOCK);
    put(&dir, "Cargo.toml", "[workspace\n");
    assert!(matches!(
        set_version(&dir, &v("0.2.7")),
        Err(Error::Failed(m)) if m.starts_with("Cargo.toml: ")
    ));
    put(
        &dir,
        "Cargo.toml",
        "[workspace.package]\nversion = \"0.1.0\"\n",
    );
    assert_eq!(
        set_version(&dir, &v("0.2.7")),
        Err(Error::Failed(
            "Cargo.toml has no [workspace] members array".to_owned()
        ))
    );
    put(&dir, "Cargo.toml", "[workspace]\nmembers = [3]\n");
    assert_eq!(
        set_version(&dir, &v("0.2.7")),
        Err(Error::Failed(
            "Cargo.toml: the member 3 is not a path".to_owned()
        ))
    );
}

/// Catches: a glob member whose directory is absent, a member manifest that is absent or not
/// TOML, or one without a package name, being skipped.
#[test]
fn a_broken_member_is_refused() {
    let dir = scratch("set-version-bad-member");
    put(&dir, "Cargo.lock", LOCK);
    put(
        &dir,
        "Cargo.toml",
        "[workspace]\nmembers = [\"nothing/*\"]\n[workspace.package]\nversion = \"0.1.0\"\n",
    );
    let path = dir.join("nothing");
    assert_eq!(
        set_version(&dir, &v("0.2.7")),
        Err(Error::Io {
            what: format!("read {}", path.display()),
            why: std::fs::read_dir(&path).expect_err("absent").to_string(),
        })
    );
    put(
        &dir,
        "Cargo.toml",
        "[workspace]\nmembers = [\"m\"]\n[workspace.package]\nversion = \"0.1.0\"\n",
    );
    let manifest = dir.join("m/Cargo.toml");
    assert_eq!(
        set_version(&dir, &v("0.2.7")),
        Err(Error::Io {
            what: format!("read {}", manifest.display()),
            why: std::fs::read_to_string(&manifest)
                .expect_err("absent")
                .to_string(),
        })
    );
    put(&dir, "m/Cargo.toml", "[package\n");
    assert!(matches!(
        set_version(&dir, &v("0.2.7")),
        Err(Error::Failed(m)) if m.starts_with("m/Cargo.toml: ")
    ));
    put(
        &dir,
        "m/Cargo.toml",
        "[package]\nversion.workspace = true\n",
    );
    assert_eq!(
        set_version(&dir, &v("0.2.7")),
        Err(Error::Failed("m/Cargo.toml has no package name".to_owned()))
    );
}
