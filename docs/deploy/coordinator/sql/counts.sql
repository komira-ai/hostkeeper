  (7, 'host_group_packages', (SELECT count(*) FROM host_group_packages)),
  (8, 'group_desired', (SELECT count(*) FROM group_desired)),
  (9, 'services', (SELECT count(*) FROM services)),
  (10, 'bad_versions', (SELECT count(*) FROM bad_versions)),
  (11, 'failure_acks', (SELECT count(*) FROM failure_acks)),
  (12, 'host_labels', (SELECT count(*) FROM host_labels)),
  (13, 'exclusions', (SELECT count(*) FROM exclusions)),
  (14, 'holds', (SELECT count(*) FROM holds)),
  (15, 'assignments', (SELECT count(*) FROM assignments)),
  (16, 'min_versions', (SELECT count(*) FROM min_versions)),
  (17, 'uninstall_intents', (SELECT count(*) FROM uninstall_intents)),
  (18, 'inventory', (SELECT count(*) FROM inventory)),
  (19, 'halts', (SELECT count(*) FROM halts)),
  (20, 'halt_reports', (SELECT count(*) FROM halt_reports)),
  (21, 'rollouts', (SELECT count(*) FROM rollouts)),
